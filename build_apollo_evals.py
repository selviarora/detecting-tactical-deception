"""
Apollo's other two main evals, in the same shape as apollo_roleplaying.

The fix in fix_probe.py is only tested on roleplaying. Their paper's main
claims are on insider trading and sandbagging, and their repo ships graded
rollouts for both, so the fix can be checked on their whole suite without
running their grading pipeline.

  apollo_sandbagging.jsonl   sandbagging_v2 / wmdp_mmlu, llama-3.3-70b,
                             on-policy. 1000 rollouts, grader keeps
                             honest / deceptive, drops ambiguous + skip.
  apollo_insider.jsonl       insider_trading / onpolicy, llama-3.1-70b.
                             173 rollouts. their repo has no graded 3.3 set
                             for this eval (the 3.3 file is empty), so this
                             is OFF-POLICY for 3.3: transcripts generated by
                             3.1, activations read from 3.3. say so.

Rows carry the full input as `messages` (insider trading is multi-turn with
tool calls) plus the graded `assistant` completion and a `label`.
capture_ood.py --which evals reads these.

Rollout files come from
github.com/ApolloResearch/deception-detection/data/rollouts/. Set
CVO_APOLLO_DATA to the repo's data/ dir, or let this fetch them.
"""

import json
import os
import urllib.request
from pathlib import Path

ROOT = Path(__file__).parent
RAW = ("https://raw.githubusercontent.com/ApolloResearch/deception-detection/"
       "main/data/rollouts/")
APOLLO_DATA = Path(os.environ.get("CVO_APOLLO_DATA", ROOT / "apollo_data" / "data"))

EVALS = {
    "sandbagging": "sandbagging_v2__wmdp_mmlu__llama-70b-3.3.json",
    "insider": "insider_trading__onpolicy__llama-70b.json",
}


def fetch(fname):
    local = APOLLO_DATA / "rollouts" / fname
    if local.exists():
        return json.load(local.open())
    cache = ROOT / "data" / "apollo_rollouts" / fname
    if not cache.exists():
        cache.parent.mkdir(parents=True, exist_ok=True)
        urllib.request.urlretrieve(RAW + fname, cache)
    return json.load(cache.open())


def build(name):
    d = fetch(EVALS[name])
    rows, uid = [], 0
    for i, r in enumerate(d["rollouts"]):
        label = (r.get("graded_deception") or [None])[0]
        if label not in ("honest", "deceptive"):
            continue
        rows.append({
            "uid": uid, "scenario_id": i, "label": label,
            "messages": r["input_messages"],
            "assistant": r["output_strs"][0],
            "source_model": d["model"],
        })
        uid += 1
    return rows


def main():
    from collections import Counter
    for name in EVALS:
        rows = build(name)
        p = ROOT / "data" / f"apollo_{name}.jsonl"
        with p.open("w") as f:
            for r in rows:
                f.write(json.dumps(r) + "\n")
        print(f"wrote {len(rows)} -> {p}  "
              f"{dict(Counter(r['label'] for r in rows))}  "
              f"(generated by {rows[0]['source_model']})")


if __name__ == "__main__":
    main()
